"""
EyePACS Dataset for Self-Supervised Pretraining.

Loads fundus images from EyePACS dataset along with pre-computed lesion
pseudo-labels (from classical lesion detection). Provides contrastive
augmentation (two augmented views per image) for SimCLR-style training.

Returns per sample:
  - view1: (3, img_size, img_size) — first augmented view
  - view2: (3, img_size, img_size) — second augmented view
  - lesion_mask: (3, mask_size, mask_size) — binary lesion masks
  - lesion_count: (3,) — lesion counts per type
  - lesion_presence: (3,) — binary presence per type
  - lesion_heatmap: (1, mask_size, mask_size) — density heatmap

Author: RetiNA-Net Project
"""

import os
import cv2
import numpy as np
import torch
from torch.utils.data import Dataset
from glob import glob
import albumentations as A
from albumentations.pytorch import ToTensorV2


# ImageNet normalization (matches pretrained backbone)
IMAGENET_MEAN = [0.485, 0.456, 0.406]
IMAGENET_STD = [0.229, 0.224, 0.225]


def get_ssl_transforms(img_size=512):
    """
    Augmentation pipeline for SSL contrastive pretraining.
    Two views are generated by applying this transform twice (stochastic).

    IMPORTANT: No vertical flip or rotation — fundus images have canonical
    vertical orientation (optic disc on one side, macula in center).

    Args:
        img_size: Target image size

    Returns:
        Albumentations Compose pipeline
    """
    return A.Compose([
        A.RandomResizedCrop(size=(img_size, img_size), scale=(0.5, 1.0), ratio=(0.8, 1.2)),

        A.HorizontalFlip(p=0.5),
        A.ColorJitter(brightness=0.4, contrast=0.4, saturation=0.2, hue=0.05, p=0.8),
        A.GaussianBlur(blur_limit=(3, 7), p=0.5),
        A.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD),
        ToTensorV2(),
    ])


class EyePACSDataset(Dataset):
    """
    EyePACS dataset for SSL pretraining with lesion pseudo-labels.

    Each sample produces two augmented views (for contrastive learning)
    plus the lesion pseudo-labels (for multi-task learning).

    The dataset loads images from image_dirs and corresponding lesion
    labels from lesion_label_dir (.npz files).
    """

    def __init__(self, image_dirs, lesion_label_dir, img_size=512, mask_size=128,
                 extensions=('.jpeg', '.jpg', '.png')):
        """
        Args:
            image_dirs: List of directories containing EyePACS images
            lesion_label_dir: Directory containing .npz lesion label files
            img_size: Image size for training
            mask_size: Lesion mask size (must match detection output)
            extensions: Valid image extensions
        """
        self.img_size = img_size
        self.mask_size = mask_size
        self.transform = get_ssl_transforms(img_size)

        # Collect all valid image paths (must have corresponding .npz label)
        self.samples = []
        if isinstance(image_dirs, str):
            image_dirs = [image_dirs]

        for img_dir in image_dirs:
            for ext in extensions:
                for img_path in glob(os.path.join(img_dir, f'*{ext}')):
                    basename = os.path.splitext(os.path.basename(img_path))[0]
                    label_path = os.path.join(lesion_label_dir, basename + '.npz')
                    if os.path.exists(label_path):
                        self.samples.append((img_path, label_path))

        if len(self.samples) == 0:
            raise ValueError(
                f"No valid samples found! Check that image_dirs={image_dirs} "
                f"and lesion_label_dir={lesion_label_dir} are correct and "
                f"that lesion detection has been run first."
            )

        print(f"EyePACS SSL Dataset: {len(self.samples)} images with lesion labels")

    def __len__(self):
        return len(self.samples)

    def _load_image(self, img_path):
        """Load and preprocess fundus image (fundus crop + CLAHE + Ben Graham)."""
        img = cv2.imread(img_path)
        if img is None:
            # Fallback: return black image
            return np.zeros((self.img_size, self.img_size, 3), dtype=np.uint8)

        # Fundus circle cropping
        img = self._crop_fundus(img)

        # Ben Graham preprocessing: Gaussian blur subtraction
        img = self._ben_graham(img)

        return img

    def _crop_fundus(self, img):
        """Crop the circular fundus region from black background."""
        gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
        _, thresh = cv2.threshold(gray, 10, 255, cv2.THRESH_BINARY)
        contours, _ = cv2.findContours(thresh, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        if contours:
            largest = max(contours, key=cv2.contourArea)
            x, y, w, h = cv2.boundingRect(largest)
            margin = 5
            x = max(0, x - margin)
            y = max(0, y - margin)
            w = min(img.shape[1] - x, w + 2 * margin)
            h = min(img.shape[0] - y, h + 2 * margin)
            img = img[y:y + h, x:x + w]
        return img

    def _ben_graham(self, img):
        """Ben Graham preprocessing: subtract Gaussian blur to enhance lesions."""
        blur = cv2.GaussianBlur(img, (0, 0), sigmaX=10)
        img = cv2.addWeighted(img, 4, blur, -4, 128)
        return img

    def _load_lesion_labels(self, label_path):
        """Load pre-computed lesion pseudo-labels from .npz file."""
        data = np.load(label_path)
        mask = data['mask']          # (mask_size, mask_size, 3)
        count = data['count']        # (3,)
        presence = data['presence']  # (3,)
        heatmap = data['heatmap']    # (mask_size, mask_size)
        return mask, count, presence, heatmap

    def __getitem__(self, idx):
        img_path, label_path = self.samples[idx]

        # Load and preprocess image
        img = self._load_image(img_path)
        img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

        # Generate two augmented views (contrastive)
        view1 = self.transform(image=img)['image']
        view2 = self.transform(image=img)['image']

        # Load lesion pseudo-labels
        mask, count, presence, heatmap = self._load_lesion_labels(label_path)

        # Convert to tensors
        # mask: (H, W, 3) → (3, H, W)
        mask_tensor = torch.from_numpy(mask).permute(2, 0, 1).float()
        count_tensor = torch.from_numpy(count).float()
        presence_tensor = torch.from_numpy(presence).float()
        # heatmap: (H, W) → (1, H, W)
        heatmap_tensor = torch.from_numpy(heatmap).unsqueeze(0).float()

        return {
            'view1': view1,              # (3, img_size, img_size)
            'view2': view2,              # (3, img_size, img_size)
            'lesion_mask': mask_tensor,   # (3, mask_size, mask_size)
            'lesion_count': count_tensor, # (3,)
            'lesion_presence': presence_tensor,  # (3,)
            'lesion_heatmap': heatmap_tensor     # (1, mask_size, mask_size)
        }


def get_ssl_dataloader(image_dirs, lesion_label_dir, batch_size=32, num_workers=8,
                      img_size=512, mask_size=128, shuffle=True, drop_last=True):
    """
    Create DataLoader for SSL pretraining.

    Args:
        image_dirs: List of image directories
        lesion_label_dir: Directory with .npz lesion labels
        batch_size: Batch size
        num_workers: Number of data loading workers
        img_size: Image size
        mask_size: Lesion mask size
        shuffle: Whether to shuffle
        drop_last: Whether to drop last incomplete batch

    Returns:
        DataLoader instance
    """
    dataset = EyePACSDataset(
        image_dirs=image_dirs,
        lesion_label_dir=lesion_label_dir,
        img_size=img_size,
        mask_size=mask_size
    )

    loader = torch.utils.data.DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        pin_memory=True,
        drop_last=drop_last,
        persistent_workers=(num_workers > 0)
    )

    return loader
